def seasons_word(n: int) -> str:
    """1 сезон, 2 сезона, 5 сезонов."""
    if n % 10 == 1 and n % 100 != 11:
        return "сезон"
    if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14):
        return "сезона"
    return "сезонов"


def films_word(n: int) -> str:
    """1 фильм, 2 фильма, 5 фильмов."""
    if n % 10 == 1 and n % 100 != 11:
        return "фильм"
    if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14):
        return "фильма"
    return "фильмов"


